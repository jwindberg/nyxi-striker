//! The Striker's keys: where each one is drawn and which slot of the keyboard's per-key tables
//! (key map, per-key colors) it uses. Generated from the official app's layout and default key
//! map for this model; positions are in its drawing units, y growing downward. The Fn key has no
//! slot and is left out.

#[derive(Debug, Clone, serde::Serialize)]
pub struct Key {
    pub label: &'static str,
    pub slot: u8,
    pub x: u16,
    pub y: u16,
    pub w: u16,
    pub h: u16,
}

const fn k(label: &'static str, slot: u8, x: u16, y: u16, w: u16, h: u16) -> Key {
    Key { label, slot, x, y, w, h }
}

